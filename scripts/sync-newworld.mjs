import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
const check = args.includes('--check');
const sourceArg = args.indexOf('--source');
if (sourceArg >= 0 && !args[sourceArg + 1]) throw new Error('--source requires a NewWorld project path');
const source = path.resolve(sourceArg >= 0 ? args[sourceArg + 1] : (process.env.NEWWORLD_PATH || 'D:/NewWorld'));
const files = ['cards.json', 'specialCards.json'];
const snapshots = [];

for (const filename of files) {
    const sourcePath = path.join(source, 'Assets', 'Resources', filename);
    const data = JSON.parse((await readFile(sourcePath, 'utf8')).replace(/^\uFEFF/, ''));
    if (!Array.isArray(data.cards)) throw new Error(`${sourcePath}: cards must be an array`);
    snapshots.push(data);
}

const ids = new Set();
for (const card of snapshots.flatMap(data => data.cards)) {
    if (!card.id || ids.has(card.id)) throw new Error(`Missing or duplicate card id: ${card.id}`);
    if (!['Attack', 'Skill', 'Core'].includes(card.type)) throw new Error(`${card.id}: unsupported CardType ${card.type}`);
    ids.add(card.id);
}

const outputs = files.map((filename, index) => [
    path.join(root, 'js', 'data', filename), `${JSON.stringify(snapshots[index], null, 2)}\n`
]);
const dataVersion = createHash('sha256').update(JSON.stringify(snapshots)).digest('hex');
outputs.push([
    path.join(root, 'js', 'newworld-cards.js'),
    '// Generated by scripts/sync-newworld.mjs. Edit the NewWorld source data, then sync.\n'
        + `export const newWorldDataVersion = '${dataVersion}';\n\n`
        + `export const newWorldCards = ${JSON.stringify(snapshots[0].cards, null, 2)};\n\n`
        + `export const newWorldSpecialCards = ${JSON.stringify(snapshots[1].cards, null, 2)};\n`
]);

let stale = false;
for (const [filename, content] of outputs) {
    let current;
    try { current = await readFile(filename, 'utf8'); }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (current === content) continue;
    if (check) {
        console.error(`Out of date: ${path.relative(root, filename)}`);
        stale = true;
    } else {
        await mkdir(path.dirname(filename), { recursive: true });
        await writeFile(filename, content, 'utf8');
    }
}

if (stale) process.exitCode = 1;
else console.log(`${check ? 'Verified' : 'Synced'} ${snapshots[0].cards.length} cards and ${snapshots[1].cards.length} special cards from ${source}`);
